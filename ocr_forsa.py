import fitz
import pytesseract
from PIL import Image
import cv2
import numpy as np
import os
import json
import io

# ----------------
# PATHS
# ----------------
PDF_BASE_PATH = "/content"
JSON_PATH = "/content/ngbss_parsed.json"
OUTPUT_JSON = "/content/ngbss_parsed_updated.json"

# ----------------
# UI HINTS
# ----------------
UI_HINTS = {
    "action_buttons": [
        "ok", "yes", "no", "cancel", "submit", "valider", "confirmer",
        "rechercher", "search", "continuer", "next", "suivant",
        "payer maintenant", "paiement", "payment", "ajouter", "add",
        "soumettre", "imprimer", "print", "fermer", "close",
        "annuler", "modifier", "save"
    ],
    "status_messages": [
        "success", "succès", "erreur", "failed", "effectuée",
        "complété", "actif", "inactif", "en attente", "validité"
    ],
    "form_fields": [
        "amount", "montant", "date", "client", "customer",
        "id", "msisdn", "nom", "prénom", "adresse",
        "numéro", "mobile", "mode de paiement", "espèces",
        "chèque", "virement", "mot de passe"
    ],
    "navigation": [
        "menu", "dashboard", "offre", "client", "ressources",
        "inventaire", "gestion", "vente", "consultation"
    ]
}

# ----------------
# LOAD JSON
# ----------------
with open(JSON_PATH, "r", encoding="utf-8") as f:
    ngbss_data = json.load(f)

# ----------------
# GET LARGEST IMAGE FROM PAGE
# ----------------
def get_largest_image_from_page(doc, page):
    largest_img = None
    max_area = 0

    for img in page.get_images(full=True):
        base = doc.extract_image(img[0])
        pil_img = Image.open(io.BytesIO(base["image"]))
        area = pil_img.size[0] * pil_img.size[1]

        if area > max_area:
            max_area = area
            largest_img = pil_img

    return largest_img

# ----------------
# PREPROCESS IMAGE
# ----------------
def preprocess_ui_image(pil_img):
    img = np.array(pil_img.convert("RGB"))
    img = cv2.resize(img, None, fx=2.5, fy=2.5, interpolation=cv2.INTER_CUBIC)
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    gray = cv2.equalizeHist(gray)
    return cv2.adaptiveThreshold(
        gray, 255,
        cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
        cv2.THRESH_BINARY, 11, 2
    )

# ----------------
# OCR CONFIG
# ----------------
TESS_CONFIG = r"--oem 3 --psm 11"

# ----------------
# STRUCTURE OCR USING UI HINTS
# ----------------
def structure_ocr_lines(lines):
    structured = {k: [] for k in UI_HINTS}
    structured["other"] = []

    for line in lines:
        l = line.lower()
        matched = False
        for category, keywords in UI_HINTS.items():
            if any(k in l for k in keywords):
                structured[category].append(line)
                matched = True
                break
        if not matched:
            structured["other"].append(line)

    return structured

# ----------------
# OCR ALL PAGES (PROCESS LEVEL)
# ----------------
def ocr_process_images(doc):
    results = []
    image_id = 1

    for page_num in range(len(doc)):
        page = doc[page_num]
        img = get_largest_image_from_page(doc, page)

        if img is None:
            continue

        processed = preprocess_ui_image(img)
        raw = pytesseract.image_to_string(
            processed,
            lang="eng+fra",
            config=TESS_CONFIG
        )

        lines = [l.strip() for l in raw.split("\n") if len(l.strip()) >= 3]
        if not lines:
            continue

        structured = structure_ocr_lines(lines)

        print(f"\n📄 Page {page_num} → Image {image_id}")
        for k, v in structured.items():
            if v:
                print(f"  - {k}:")
                for item in v:
                    print(f"     • {item}")

        results.append({
            "image": image_id,
            "page": page_num,
            "ui_elements": structured
        })

        image_id += 1

    return results

# ----------------
# MAIN LOOP (PROCESS LEVEL)
# ----------------
for guide in ngbss_data:
    pdf_path = os.path.join(PDF_BASE_PATH, guide["file_name"])
    if not os.path.exists(pdf_path):
        print(f"⚠️ Missing PDF: {guide['file_name']}")
        continue

    print(f"\n==============================")
    print(f"PROCESSING GUIDE: {guide['file_name']}")
    print(f"==============================")

    doc = fitz.open(pdf_path)

    guide["illustration_text"] = ocr_process_images(doc)

# ----------------
# SAVE UPDATED JSON
# ----------------
with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
    json.dump(ngbss_data, f, ensure_ascii=False, indent=2)

print("\n✅ DONE. Process-level illustration text saved to:", OUTPUT_JSON)

